/* ---------- توابع کمکی نمایش ریاضی ----------
   فرمول‌ها با LaTeX نوشته و با KaTeX نمایش داده می‌شوند:
     M(...)  → فرمول (بین $ ... $)     F(a, b) → \frac{a}{b}     P(b, e) → b^{e}
     E('3x^2y-5')  → LaTeX از نوشتن ساده (^ توان، * ضرب؛ ^{...} برای توان چندکاراکتری)
     X('...')      → M(E('...'))  یعنی فرمول آمادهٔ نمایش
   رقم‌ها به‌طور خودکار فارسی می‌شوند. */
function F(n, d) { return '\\frac{' + n + '}{' + d + '}'; }
function M(s) { return '$' + s + '$'; }
function P(b, e) { return b + '^{' + e + '}'; }
function E(s) {
  var out = '', i = 0, c, m, tok, k;
  while (i < s.length) {
    c = s.charAt(i);
    if (c === '&') { k = s.indexOf(';', i); out += s.slice(i, k + 1); i = k + 1; }
    else if (c === '^') {
      if (s.charAt(i + 1) === '{') { k = s.indexOf('}', i + 1); tok = s.slice(i + 2, k); i = k + 1; }
      else { m = /^-?([0-9]+|[a-z])/.exec(s.slice(i + 1)); tok = m[0]; i = i + 1 + tok.length; }
      out += '^{' + E(tok) + '}';
    } else if (c === '*') { out += '× '; i++; }
    else { out += c; i++; }
  }
  return out;
}
function X(s) { return M(E(s)); }
function LTR(s) { return '\u2066' + s + '\u2069'; }   // متن چپ‌به‌راست داخل منوی کشویی

/* TABLE: جدول ساده؛ سطر اول و ستون اول سرستون‌اند */
function TABLE(rows) {
  var h = '<div class="tblwrap"><table class="dt">', i, j;
  for (i = 0; i < rows.length; i++) {
    h += '<tr>';
    for (j = 0; j < rows[i].length; j++) {
      h += (i === 0 || j === 0 ? '<th>' : '<td>') + rows[i][j] + (i === 0 || j === 0 ? '</th>' : '</td>');
    }
    h += '</tr>';
  }
  return h + '</table></div>';
}

/* BAR: نمودار ستونی با عنوان، محور و مقیاس روشن (SVG با ویژگی‌های درون‌خطی)
   o = { title, cats:[...], vals:[...], ymax, step, yTitle, showVals } */
function BAR(o) {
  var W = 340, H = 250, L = 46, R = 14, T = 40, B = 44, pw = W - L - R, ph = H - T - B, n = o.cats.length, i, v, s, slot, bw, x, h, y;
  function py(val) { return T + ph - val / o.ymax * ph; }
  s = '<svg viewBox="0 0 ' + W + ' ' + H + '" width="' + W + '" height="' + H + '" xmlns="http://www.w3.org/2000/svg" ' +
    'style="direction:ltr;max-width:100%;height:auto;display:block;margin:6px auto" role="img">';
  s += '<text x="' + (W / 2) + '" y="18" text-anchor="middle" font-size="14" font-weight="bold" fill="#14213d" font-family="Tahoma,sans-serif">' + o.title + '</text>';
  if (o.yTitle) {
    s += '<text x="' + L + '" y="34" text-anchor="end" font-size="11" fill="#14213d" font-family="Tahoma,sans-serif">' + o.yTitle + '</text>';
  }
  for (v = 0; v <= o.ymax + 1e-9; v += o.step) {
    s += '<line x1="' + L + '" y1="' + py(v) + '" x2="' + (W - R) + '" y2="' + py(v) + '" stroke="' + (v === 0 ? '#14213d' : '#d5dde8') + '" stroke-width="' + (v === 0 ? 2 : 1) + '"/>';
    s += '<text x="' + (L - 6) + '" y="' + (py(v) + 4) + '" text-anchor="end" font-size="11" fill="#14213d" font-family="Tahoma,sans-serif">' + v + '</text>';
  }
  s += '<line x1="' + L + '" y1="' + T + '" x2="' + L + '" y2="' + py(0) + '" stroke="#14213d" stroke-width="2"/>';
  slot = pw / n; bw = slot * 0.5;
  for (i = 0; i < n; i++) {
    x = L + i * slot + (slot - bw) / 2; h = o.vals[i] / o.ymax * ph; y = T + ph - h;
    s += '<rect x="' + x + '" y="' + y + '" width="' + bw + '" height="' + h + '" fill="#0e8f7e" stroke="#14213d" stroke-width="1.5"/>';
    s += '<text x="' + (x + bw / 2) + '" y="' + (py(0) + 18) + '" text-anchor="middle" font-size="12" fill="#14213d" font-family="Tahoma,sans-serif">' + o.cats[i] + '</text>';
    if (o.showVals) {
      s += '<text x="' + (x + bw / 2) + '" y="' + (y - 5) + '" text-anchor="middle" font-size="12" font-weight="bold" fill="#14213d" font-family="Tahoma,sans-serif">' + o.vals[i] + '</text>';
    }
  }
  return s + '</svg>';
}

